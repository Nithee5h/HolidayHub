import '@testing-library/jest-dom/vitest';
import { cleanup, configure } from '@testing-library/react';
import { afterEach } from 'vitest';

afterEach(() => cleanup());

// Step transitions + lazily loaded routes can take >1s under a parallel full-suite run.
configure({ asyncUtilTimeout: 3000 });

// jsdom lacks these browser APIs used by Motion and our hooks.
class IntersectionObserverStub {
  observe() {}
  unobserve() {}
  disconnect() {}
  takeRecords() {
    return [];
  }
}
globalThis.IntersectionObserver ??= IntersectionObserverStub;
window.matchMedia ??= (query) => ({
  matches: false,
  media: query,
  onchange: null,
  addEventListener() {},
  removeEventListener() {},
  addListener() {},
  removeListener() {},
  dispatchEvent: () => false,
});
window.scrollTo = () => {};
Element.prototype.scrollIntoView ??= function scrollIntoView() {};
